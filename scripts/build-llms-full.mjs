#!/usr/bin/env node
/**
 * Regenerates `llms-full.txt` — a single-file export of the project documentation for one-shot
 * LLM ingestion. It concatenates the source docs (below) with stable separators.
 *
 * Run: `node scripts/build-llms-full.mjs`  (or `npm run docs:llms-full` / `yarn docs:llms-full`).
 *
 * Deterministic by design (no timestamps), so CI can verify the committed file is in sync via:
 *   node scripts/build-llms-full.mjs && git diff --exit-code -- llms-full.txt
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Source docs concatenated into the export, in order. Keep in sync with llms.txt's primary docs.
const SOURCES = ['README.md', 'docs/logging.md', 'CHANGELOG.md'];

const out = [
	'# observer-js (@observertc/observer-js) — full documentation',
	'',
	"> Single-file export of the project's documentation for one-shot LLM ingestion.",
	`> Concatenates: ${SOURCES.join(', ')}. Generated by scripts/build-llms-full.mjs —`,
	'> the canonical, always-current copies live in the repository; see llms.txt for the link index.',
];

for (const rel of SOURCES) {
	const body = readFileSync(join(root, rel), 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '');
	out.push(
		'',
		'---',
		'',
		'# ============================================================================',
		`# ${rel}`,
		'# ============================================================================',
		'',
		body,
	);
}

writeFileSync(join(root, 'llms-full.txt'), out.join('\n') + '\n');
console.log(`Wrote llms-full.txt from: ${SOURCES.join(', ')}`);
